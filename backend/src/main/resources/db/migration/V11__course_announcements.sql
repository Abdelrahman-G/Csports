CREATE TABLE course_announcement (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    course_id BIGINT NOT NULL,
    author_id BIGINT NOT NULL,
    type VARCHAR(32) NOT NULL,
    title VARCHAR(150) NOT NULL,
    content VARCHAR(2000) NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_announcement_course FOREIGN KEY (course_id) REFERENCES training_course(id),
    CONSTRAINT fk_announcement_author FOREIGN KEY (author_id) REFERENCES users(id),
    CONSTRAINT chk_announcement_type CHECK (type IN ('TRAINER_MESSAGE','COURSE_UPDATED','COURSE_CANCELLED'))
);
CREATE INDEX idx_announcement_course_created ON course_announcement(course_id, created_at DESC, id DESC);
ALTER TABLE user_notification ADD COLUMN announcement_id BIGINT;
ALTER TABLE user_notification ADD CONSTRAINT fk_notification_announcement
    FOREIGN KEY (announcement_id) REFERENCES course_announcement(id);
ALTER TABLE user_notification DROP CONSTRAINT chk_user_notification_type;
ALTER TABLE user_notification ADD CONSTRAINT chk_user_notification_type
    CHECK (type IN ('COURSE_UPDATED','COURSE_CANCELLED','COURSE_ANNOUNCEMENT'));
